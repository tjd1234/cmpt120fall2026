"""
Draw a square on the screen using turtle graphics.
Make sure the screen does
*not* close when the program ends.

"""
import turtle
import random

turtle.right(random.randint(1, 100))

turtle.forward(100)
turtle.right(90)
turtle.forward(100)
turtle.right(90)
turtle.forward(100)
turtle.right(90)
turtle.forward(100)

turtle.forward(100)
turtle.right(90)
turtle.forward(100)
turtle.right(90)
turtle.forward(100)
turtle.right(90)
turtle.forward(100)

turtle.done()
